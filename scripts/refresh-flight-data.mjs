import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { completeAirportDirectory } from './complete-airport-directory.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const today = process.argv[2] || new Intl.DateTimeFormat('en-CA', { timeZone: 'Europe/Berlin', year: 'numeric', month: '2-digit', day: '2-digit' }).format(new Date());
if (!/^\d{4}-\d{2}-\d{2}$/.test(today)) throw new Error('Expected YYYY-MM-DD');
const monday = new Date(`${today}T12:00:00Z`);
monday.setUTCDate(monday.getUTCDate() - (monday.getUTCDay() + 6) % 7);
const dates = Array.from({ length: 7 }, (_, i) => { const date = new Date(monday); date.setUTCDate(date.getUTCDate() + i); return date.toISOString().slice(0, 10); });
const failures = [];
const records = new Map();
const coverage = new Map(dates.map(date => [date, 0]));
const jobs = dates.flatMap(date => ['arrivals', 'departures'].flatMap(direction => [0, 6, 12, 18].map(hour => ({ date, direction, hour }))));
async function fetchWindow({ date, direction, hour }) {
  const [year, month, day] = date.split('-').map(Number);
  const url = new URL(`https://www.flightstats.com/v2/flight-tracker/${direction}/FRA`);
  url.search = new URLSearchParams({ year, month, date: day, hour, numHours: 6, utc: false, showCodeshares: false });
  const response = await fetch(url, { signal: AbortSignal.timeout(25000) });
  if (!response.ok) throw new Error(`HTTP ${response.status}`);
  const html = await response.text();
  const match = html.match(/__NEXT_DATA__\s*=\s*(\{.*?\});__NEXT_LOADED_PAGES__/s);
  if (!match) throw new Error('Flight board data missing');
  const board = JSON.parse(match[1]).props?.initialState?.flightTracker?.route;
  const expectedDate = `${String(day).padStart(2, '0')}-${['Jan','Feb','Mar','Apr','May','Jun','Jul','Aug','Sep','Oct','Nov','Dec'][month - 1]}-${year}`;
  if (board?.header?.date !== expectedDate || !Array.isArray(board.flights)) throw new Error('Requested date unavailable');
  for (const flight of board.flights) {
    if (flight.isCodeshare || !flight.airport?.fs || !flight.carrier?.fs) continue;
    const code = String(flight.carrier.fs).replaceAll('*', '');
    const record = [date, direction === 'arrivals' ? 'A' : 'D', flight.airport.fs, flight.departureTime?.time24 || '—', flight.arrivalTime?.time24 || '—', `${code} ${flight.carrier.flightNumber}`, flight.carrier.name];
    // Overlapping windows and codeshares must not multiply the board counts.
    records.set(`${date}-${direction}-${flight.url || `${record[5]}-${record[2]}`}`, record);
  }
  coverage.set(date, coverage.get(date) + 1);
}
await Promise.all(Array.from({ length: 3 }, async () => {
  while (jobs.length) {
    const job = jobs.shift();
    try { await fetchWindow(job); }
    catch (error) { failures.push({ ...job, reason: error.message }); }
  }
}));
const completeDates = dates.filter(date => coverage.get(date) === 8);
if (!completeDates.includes(today)) throw new Error(`Today's board could not be refreshed completely. Existing data preserved. ${JSON.stringify(failures.filter(f => f.date === today))}`);
const flights = [...new Map([...records.values()].map(record => [JSON.stringify(record), record])).values()].filter(record => completeDates.includes(record[0]) && record[2] !== 'FRA').sort((a, b) => a[0].localeCompare(b[0]) || a[1].localeCompare(b[1]) || a[3].localeCompare(b[3]));
for (const date of completeDates) if (flights.filter(f => f[0] === date).length < 100) throw new Error(`Suspiciously incomplete board for ${date}; existing data preserved.`);
const metadata = { refreshedAt: new Date().toISOString(), selectedDate: today, dates, availableDates: completeDates, source: 'FlightStats public FRA boards', sourceUrl: 'https://www.flightstats.com/v2/flight-tracker/departures/FRA', recordCount: flights.length, routeDirectoryEdition: 'August 2026', failures };
const output = `// Generated by npm run refresh:data. Times are the source board's airport-local times.\nexport type FlightRecord = [date: string, direction: 'A' | 'D', iata: string, departureTime: string, arrivalTime: string, number: string, airline: string];\n\nexport const flights: FlightRecord[] = ${JSON.stringify(flights)};\n`;
const routeOutput = await completeAirportDirectory(root, flights);
await fs.writeFile(path.join(root, 'app/routes.ts'), routeOutput);
await fs.writeFile(path.join(root, 'app/flights.ts'), output);
await fs.writeFile(path.join(root, 'app/flight-data-meta.json'), `${JSON.stringify(metadata, null, 2)}\n`);
console.log(JSON.stringify({ records: flights.length, dates: completeDates, skippedWindows: failures.length, refreshedAt: metadata.refreshedAt }, null, 2));
